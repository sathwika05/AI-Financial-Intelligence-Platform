from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Literal
from uuid import UUID, uuid4

from pydantic import BaseModel, Field

# Safe to import: claims.audit depends on pydantic only, so there is no
# cycle back into this module.
from backend.evaluation.claims.audit import ClaimAudit


class IntentType(str, Enum):
    """Supported financial query routes."""

    VALUATION = "VALUATION"
    GROWTH = "GROWTH"
    SENTIMENT = "SENTIMENT"
    MIXED = "MIXED"


class BenchmarkStatus(str, Enum):
    """Lifecycle states persisted in benchmark_runs.status."""

    QUEUED = "queued"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"

    # Stopped on purpose. Distinct from FAILED, which means the run broke:
    # a cancelled run's scored questions are valid, there are just fewer
    # of them than the question set holds.
    CANCELLED = "cancelled"


class BenchmarkConfig(BaseModel):
    """
    Internal benchmark configuration.

    The UI sends provider_id only for LLM selection.
    evaluation_routes.py resolves that provider's small, medium,
    and large models and stores the resolved snapshot in `model`.
    """

    dataset: str
    question_set: str

    # Readable runtime snapshot generated by the backend.
    # Example:
    # small=gpt-5.4-nano, medium=gpt-5.4-mini, large=gpt-5.6-sol
    model: str

    retrieval_strategy: str
    company_filter: str = "all"

    top_k: int = Field(
        default=5,
        ge=1,
        le=100,
    )

    benchmark_version: str = "v1"
    dataset_version: str = "v1"


class EvalQuestion(BaseModel):
    """One golden question loaded from the selected question set."""

    question_id: str
    question: str

    expected_intent: IntentType

    # Expected LangGraph/tool names for ToolEvaluator.
    expected_tools: list[str] = Field(
        default_factory=list
    )

    # Reference values used by RAGAS.
    reference_answer: str | None = None
    reference_contexts: list[str] = Field(
        default_factory=list
    )

    # Expected SQL artifacts used by SQLEvaluator.
    expected_sql: str | None = None
    expected_sql_result: Any | None = None

    # What the question makes the SQL node responsible for, orderwise.
    #
    # The single source of truth for ordering semantics: both sql_accuracy
    # (result level) and sql_equivalence (query level) read this, so the two
    # primary metrics judge the same contract. Derived from the question's
    # wording and the SQL node's responsibility — never from whether the
    # golden SQL happens to contain an ORDER BY, which is incidental.
    #
    #   "none"     Row order is not part of SQL correctness. The rows are
    #              compared as a multiset. Use when the question asks SQL to
    #              retrieve or filter, or when it asks for a ranking SQL
    #              cannot compute — "rank by valuation, growth, market
    #              performance and sentiment" needs four signals, of which
    #              SQL holds two, so no ordering it produces could be the
    #              requested one.
    #
    #   "ranking"  The question asks for an order over a population SQL can
    #              sort, and SQL owns it. Same rows in the wrong order is a
    #              failure. Sort column and direction both matter.
    #
    #   "top_k"    Ordering decides membership, not just sequence. "The five
    #              lowest P/E" is not satisfied by any five rows: a bare
    #              LIMIT 5 returns five companies that are probably the wrong
    #              five. Both the K selected and their order are graded.
    #
    # Defaults to "none" so a new question cannot silently claim an ordering
    # contract it never stated. Every existing question is classified
    # explicitly rather than relying on this default — see question_sets.py.
    sql_order_requirement: Literal[
        "none",
        "ranking",
        "top_k",
    ] = "none"

    # Expected company/ticker ordering for RankingEvaluator.
    expected_ranking: list[str] = Field(
        default_factory=list
    )

    @property
    def expected_companies(self) -> list[str]:
        """
        Compatibility alias used by RankingEvaluator and MarketEvaluator.
        """
        return self.expected_ranking


class PipelineExecution(BaseModel):
    """Normalized artifacts extracted from the final FinancialState."""

    actual_intent: str | None = None

    generated_sql: str | None = None
    sql_result: Any | None = None

    # The rows the query returned, separate from sql_result's natural-language
    # `answer`. The SQL evaluator compares tables, so handing it the whole
    # result dict made it diff a golden table against a paragraph.
    sql_rows: list[Any] = Field(
        default_factory=list
    )

    retrieved_contexts: list[str] = Field(
        default_factory=list
    )
    reranked_contexts: list[str] = Field(
        default_factory=list
    )

    # The reranked contexts with the reranker's own source_type intact —
    # "vector" for a document chunk, "market" for a live price row, "sql"
    # for a result row.
    #
    # reranked_contexts above is the flattened text, and flattening lost
    # the one distinction the RAGAS context metrics need. On a MIXED
    # question the reranker returns roughly three document chunks and
    # eleven market rows; grading retrieval quality over all fourteen
    # measured the market API rather than the document corpus, and
    # context_precision read 0.1186.
    reranked_context_records: list[dict[str, Any]] = Field(
        default_factory=list
    )

    market_result: Any | None = None

    ranked_companies: list[dict[str, Any]] = Field(
        default_factory=list
    )

    executed_tools: list[str] = Field(
        default_factory=list
    )

    final_answer: Any | None = None

    latency_ms: float = 0.0
    cost_usd: float | None = None

    # One entry per node execution: {"node": ..., "latency_ms": ...}.
    node_timings: list[dict[str, Any]] = Field(
        default_factory=list
    )

    # Token usage measured across every LLM call in this question's run.
    input_tokens: int = 0
    output_tokens: int = 0
    llm_calls: int = 0

    # Useful for debugging and future per-question persistence.
    raw_state: dict[str, Any] = Field(
        default_factory=dict
    )


class EvaluatorResult(BaseModel):
    """
    Shared output contract for all six evaluators.

    Expected evaluator names:
    - intent
    - sql
    - ragas
    - tool
    - ranking
    - market
    """

    evaluator: str
    applicable: bool = True
    passed: bool | None = None

    # Optional normalized score used for per-question pass/fail.
    score: float | None = Field(
        default=None,
        ge=0.0,
        le=1.0,
    )

    metrics: dict[
        str,
        float | int | bool | None,
    ] = Field(default_factory=dict)

    details: dict[str, Any] = Field(
        default_factory=dict
    )

    errors: list[str] = Field(
        default_factory=list
    )


class QuestionEvaluationResult(BaseModel):
    """Evaluation result for one benchmark question."""

    question_id: str
    question: str

    expected_intent: str
    actual_intent: str | None = None

    execution: PipelineExecution = Field(
        default_factory=PipelineExecution
    )

    evaluator_results: dict[
        str,
        EvaluatorResult,
    ] = Field(default_factory=dict)

    # Claim-level grounding, deliberately outside evaluator_results.
    #
    # finalize_question_result averages every applicable evaluator into
    # overall_score and fails the question if any reports passed=False, so
    # an audit placed in that dict would re-score every question already
    # benchmarked. Here it is carried alongside, scores nothing, and votes
    # on nothing — see tests/test_claim_audit_does_not_gate.py.
    claim_audit: ClaimAudit | None = None

    # Flattened evaluator metrics for future detailed persistence.
    aggregate_metrics: dict[str, Any] = Field(
        default_factory=dict
    )

    overall_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
    )

    passed: bool = False
    error: str | None = None


class BenchmarkRunResult(BaseModel):
    """Complete in-memory result for one benchmark execution."""

    run_id: UUID = Field(
        default_factory=uuid4
    )

    status: BenchmarkStatus = BenchmarkStatus.QUEUED

    config: BenchmarkConfig

    started_at: datetime = Field(
        default_factory=lambda: datetime.now(
            timezone.utc
        )
    )
    completed_at: datetime | None = None

    question_results: list[
        QuestionEvaluationResult
    ] = Field(default_factory=list)

    aggregate_metrics: dict[str, Any] = Field(
        default_factory=dict
    )

    total_questions: int = Field(
        default=0,
        ge=0,
    )
    passed_questions: int = Field(
        default=0,
        ge=0,
    )
    failed_questions: int = Field(
        default=0,
        ge=0,
    )

    error: str | None = None
