# ── Dynamic Weight Calculator ───────────────────────────────

@traceable(
    name="calculate_weights",
    run_type="chain",
    tags=["scoring", "weights"],
)
def calculate_weights(
    intent:        str,
    market_result: dict = None
) -> dict:
    """
    Calculate confidence weights dynamically.
    Adjusts market weight to 0 if market data unavailable.
    Redistributes weight to SQL and Vector.
    """
    market_available = (
        market_result is not None and
        market_result.get("confidence", 0.0) > 0
    )

    if intent in SQL_INTENTS:
        return {"sql": 1.0, "vector": 0.0, "market": 0.0}

    elif intent in VECTOR_INTENTS:
        return {"sql": 0.0, "vector": 1.0, "market": 0.0}

    else:  # MIXED
        if market_available:
            return {"sql": 0.4, "vector": 0.3, "market": 0.3}
        else:
            # market unavailable — redistribute its weight
            return {"sql": 0.6, "vector": 0.4, "market": 0.0}





# ── Combine Results ─────────────────────────────────────────

@traceable(
    name="combine_results",
    run_type="chain",
    tags=["scoring", "fanin"],
)
def combine_results(
    query:         str,
    intent:        str,
    sql_result:    dict = None,
    vector_result: dict = None,
    market_result: dict = None
) -> dict:
    """
    Combine retrieval results into unified response.
    Adjusts weights when market data unavailable.
    Weights per intent:
    VALUATION → SQL 100%
    GROWTH    → SQL 100%
    SENTIMENT → Vector 100%
    MIXED     → SQL 40% + Vector 30% + Market 30%
    """

    sql_r    = sql_result    or {"confidence": 0.0}
    vector_r = vector_result or {"confidence": 0.0}
    market_r = market_result or {"confidence": 0.0}

    weights = calculate_weights(intent, market_result)

    overall_confidence = round(
        (sql_r["confidence"]    * weights["sql"])    +
        (vector_r["confidence"] * weights["vector"]) +
        (market_r["confidence"] * weights["market"]),
        3
    )

    result = {
        "query":              query,
        "intent":             intent,
        "overall_confidence": overall_confidence,
        "weights_used":       weights
    }

    if sql_result:
        result["sql_result"] = {
            "answer":     sql_result["answer"],
            "confidence": sql_result["confidence"],
            # Rows and SQL are what the hybrid reranker scores as
            # SQL evidence; dropping them here leaves it with nothing.
            "db_result":     sql_result.get("db_result", {}),
            "generated_sql": sql_result.get("generated_sql", ""),
            "error":      sql_result.get("error")
        }

    if vector_result:
        result["vector_result"] = {
            "retrieved_chunks":   vector_result["retrieved_chunks"],
            "retrieved_contexts": vector_result.get(
                "retrieved_contexts", []
            ),
            "confidence": vector_result["confidence"],
            "error":      vector_result.get("error")
        }

    if market_result:
        result["market_result"] = {
            "market_data": market_result["market_data"],
            "confidence": market_result["confidence"],
            "cached":     market_result.get("cached", False),
            "stale":      market_result.get("stale", False),
            "degraded":   market_result.get("degraded", False),
            "error":      market_result.get("error")
        }

    
    return result




# ── Main Async Hybrid Function ────────────────────────────────────

@traceable(
    name="hybrid_retrieval",
    run_type="chain",
    tags=["retrieval", "fanout"],
)
async def hybrid_retrieve_async(
    query:        str,
    intent:       str,
    sql_query:    str = None,
    vector_query: str = None,
    market_query: str = None,
    config: RunnableConfig | None = None,
    candidate_tickers: list[str] | None = None,
    candidate_company_ids: list[int] | None = None,
) -> dict:
    """
    Production-grade async hybrid retrieval.

    Features:
    - Fan-out/fan-in with asyncio.gather
    - Per-service timeouts
    - Partial results on failure
    - Dynamic weight adjustment
    - Full exception logging

    Routes:
    VALUATION → SQL only
    GROWTH    → SQL only
    SENTIMENT → Vector only
    MIXED     → SQL + Vector + Market in parallel
    """
    sql_q    = sql_query    or query
    vector_q = vector_query or query
    market_q = market_query or ""

    # The wording the SQL generator is asked, as opposed to `sql_q`, which
    # steers retrieval. The planner rewrites the question into a keyword
    # subquery — "technology companies low PE ratio undervalued market cap" —
    # which is right for search and wrong for SQL generation, because the
    # constraints the user stated do not survive it. A question asking for
    # five companies becomes one asking for none, and the generator then
    # defaults to LIMIT 10.
    #
    # SQL-only intents therefore ask the user's own question, which is
    # entirely about the metrics SQL owns. MIXED keeps the planner's subquery,
    # because there the full question also covers news and market data that
    # SQL cannot answer, and handing all of it to the SQL generator would be
    # worse than losing the count.
    sql_question = query if intent in SQL_INTENTS else sql_q

    candidate_tickers = candidate_tickers or []
    candidate_company_ids = candidate_company_ids or []

    # One eligible set for every branch. Previously each discovered its own:
    # SQL manufactured a filter from document text and returned EOG/JPM/GS
    # while the market branch resolved NVDA/MSFT/GOOGL/AMZN/META from the
    # planner's wording, and the scorer ranked the union of the two.
    if candidate_tickers:
        # Stated as a constraint on the question rather than by editing the
        # generated SQL: the generator already has a rule for honouring an
        # explicit ticker list, and rewriting its output would mean parsing
        # SQL to find the right place to intervene.
        sql_question = (
            f"{sql_question}\n\n"
            "Restrict the results to exactly these companies, which have "
            "already been determined to match the category the question "
            f"asks about: {', '.join(candidate_tickers)}. "
            "Filter with c.ticker IN (...) and do not widen the set."
        )

        # The market branch resolves tickers from free text with an LLM
        # call. Given the candidates it does not need to guess, and cannot
        # drift onto a different set — it previously answered a question
        # about AMD with AMZN.
        market_q = ", ".join(candidate_tickers)

    logger.info(
        f"[HYBRID] Intent: {intent}, "
        f"sql_q: {sql_q[:50]}, "
        f"vector_q: {vector_q[:50]}, "
        f"market_q: {market_q[:50]}, "
        f"candidates: {','.join(candidate_tickers) or 'all'}"
    )

    if intent in SQL_INTENTS:
        # VALUATION or GROWTH → SQL only
        sql_result = await run_sql_retrieval(
            sql_q,
            config,
            sql_question=sql_question,
        )
        return combine_results(
            query      = query,
            intent     = intent,
            sql_result = sql_result
        )

    elif intent in VECTOR_INTENTS:
        # SENTIMENT → Vector only
        vector_result = await run_vector_retrieval(
            vector_q,
            config,
            candidate_company_ids=candidate_company_ids,
        )
        return combine_results(
            query         = query,
            intent        = intent,
            vector_result = vector_result
        )

    else:
        # MIXED → SQL + Vector + Market API
        # MIXED — fan-out all tasks in parallel with timeout
        logger.info(
            "[HYBRID_ASYNC] Fanning out 3 tasks in parallel"
        )

        tasks = [
            run_sql_retrieval_async(
                sql_q,
                config,
                sql_question=sql_question,
            ),
            run_vector_retrieval_async(
                vector_q,
                config,
                candidate_company_ids=candidate_company_ids,
            ),
        ]

        if market_q:
            tasks.append(run_market_retrieval_async(market_q,config))

        try:
            # fan-in with overall timeout
            
            results = await asyncio.wait_for(
                asyncio.gather(*tasks, return_exceptions=True),
                timeout=60
            ) 
            
            #sql_result = await run_sql_retrieval_async(sql_q)
            #vector_result = await run_vector_retrieval_async(vector_q)
            #market_result = await run_market_retrieval_async(market_q)
        except asyncio.TimeoutError:
            logger.error("[HYBRID_ASYNC] Overall timeout after 20s")
            results = [
                {"source": "sql",    "answer": "", "confidence": 0.0, "error": "timeout"},
                {"source": "vector", "chunks": [], "confidence": 0.0, "error": "timeout"},
            ]
        

        # extract results safely
        sql_result = results[0] if (
            len(results) > 0 and
            not isinstance(results[0], Exception)
        ) else {"source": "sql", "answer": "", "confidence": 0.0, "error": "failed"}

        vector_result = results[1] if (
            len(results) > 1 and
            not isinstance(results[1], Exception)
        ) else {"source": "vector", "chunks": [], "confidence": 0.0, "error": "failed"}

        market_result = results[2] if (
            len(results) > 2 and
            not isinstance(results[2], Exception)
        ) else None

        # log exceptions
        for i, r in enumerate(results):
            if isinstance(r, Exception):
                logger.error(
                    f"[HYBRID_ASYNC] Task {i} raised: {r}",
                    exc_info=r
                )

        logger.info(
            f"[HYBRID_ASYNC] Fan-in complete. "
            f"SQL: {sql_result.get('confidence', 0)}, "
            f"Vector: {vector_result.get('confidence', 0)}, "
            f"Market: {market_result.get('confidence', 0) if market_result else 'N/A'}"
        )

        return combine_results(
            query         = query,
            intent        = intent,
            sql_result    = sql_result,
            vector_result = vector_result,
            market_result = market_result
        )