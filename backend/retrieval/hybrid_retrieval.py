@traceable(
    name="sql_retrieval",
    run_type="chain",
    tags=["retrieval", "sql"],
)
async def run_sql_retrieval(
    query: str,
    config: RunnableConfig,
    sql_question: str | None = None,
) -> dict[str, Any]:
    """
    Run SQL retrieval using the existing sql_graph.
    Returns structured results with confidence score.

    `sql_question` is the exact wording the SQL tools should be asked, and
    it is kept separate from `query` on purpose. `query` is the planner's
    subquery — keyword-shaped, written to steer retrieval — while the SQL
    generator needs the constraints the user actually stated, such as how
    many rows they asked for. Defaults to `query` when the caller has
    nothing better, which is the previous behaviour.
    """
    try:
        result = await sql_graph.ainvoke({
            "messages":          [HumanMessage(content=query)],
            "retry_count":       0,
            'original_question': '',
            'sql_question': sql_question or query,
            'last_sql': '',
            'db_result': {},
            'sql_executed_tools': []
        },
        config=config,)

        messages = result.get("messages", [])

        answer = (
            messages[-1].content
            if messages
            else ""
        )

        # SQL generated by the SQL graph
        generated_sql = result.get(
            "last_sql",
            "",
        )

        # SQL execution result
        db_result = result.get("db_result",{},)

        # SQL tools executed
        sql_executed_tools: list[str] = result.get("sql_executed_tools",[])


        confidence = 0.9 if "No companies" not in answer else 0.1
        
        logger.info("[HYBRID] SQL retrieval complete")
        return {
            "source":     "sql",
            "answer":     answer,
            "confidence": confidence,
            "generated_sql": generated_sql,
            "db_result": db_result,
            "sql_executed_tools": sql_executed_tools,
        }

    except Exception as e:
        logger.error(f"[HYBRID] SQL retrieval failed: {e}")
        return {
            "source":     "sql",
            "answer":     "",
            "confidence": 0.0,
            "generated_sql": "",
            "db_result": {},
            "sql_executed_tools": [],
            "error":      str(e),
            # The exception class, kept alongside the message so the SQL
            # boundary can log a short, low-cardinality label. Database
            # error *messages* can carry connection details, so they are
            # not what gets logged there.
            "error_type": type(e).__name__,
        }


# ── Vector Retrieval ────────────────────────────────────────

@traceable(
    name="vector_retrieval",
    run_type="chain",
    tags=["retrieval", "vector"],
)
async def run_vector_retrieval(
    query: str,
    config: RunnableConfig,
    top_k: int = 5,
    candidate_company_ids: list[int] | None = None,
) -> dict:
    """
    Run vector retrieval pipeline:
    1. Extract metadata filters from query
    2. Generate ranking keywords from query
    3. pgvector cosine similarity search with filters
    4. BM25 reranking by keyword relevance
    Returns structured result with confidence score.

    `candidate_company_ids` restricts the search to documents belonging to
    the eligible companies. Without it, retrieval for an AI question spent
    its five slots on Intel, Nike and a pharmaceutical upgrade — none of
    which belonged to any company being ranked, so relevance and sentiment
    were unmeasurable for every candidate.
    """
    try:
        filters  = await extract_filters(query,config)
        keywords = await generate_ranking_keywords(query,config)

        if candidate_company_ids:
            # Overrides any company the filter extractor inferred from the
            # wording: the candidate set was resolved from a curated
            # taxonomy and is the more reliable of the two.
            filters = {
                **(filters or {}),
                "company_ids": list(candidate_company_ids),
            }

        logger.info(
            f"[VECTOR] Vector filters: {filters}, "
            f"keywords: {keywords}"
        )

        rows = await search_similar_chunks(
            query    = query,
            top_k    = top_k,
            filters  = filters,
            keywords = keywords
        )

        if not rows:
            return {
                "source":     "vector",
                "retrieved_chunks":     [],
                "retrieved_contexts": [],
                "confidence": 0.0
            }

        retrieved_chunks = [{
            "chunk_id": row.id,
            "document_id": row.document_id,
            "content":     row.content[:600],
            "doc_type":    row.doc_type,
            "source":      row.source,
            "company_id":  row.company_id,
            "chunk_index": row.chunk_index,
            "similarity":  round(row.similarity, 3)
        } for row in rows]

        retrieved_contexts = [
            chunk["content"]
            for chunk in retrieved_chunks
        ]

        confidence = 0.8 if retrieved_chunks else 0.0

        logger.info(
            f"[HYBRID] Vector complete. "
            f"{len(retrieved_chunks)} chunks found"
        )

        return {
            "source": "vector",
            "retrieved_chunks": retrieved_chunks,
            "retrieved_contexts": retrieved_contexts,
            "confidence": confidence,
        }

    except Exception as exc:
        logger.error(f"[HYBRID] Vector retrieval failed: {exc}")
        return {
            "source": "vector",
            "retrieved_chunks": [],
            "retrieved_contexts": [],
            "confidence": 0.0,
            "error": str(exc),
        }

# ── Async Wrappers with Timeouts ────────────────────────────

@traceable(
    name="branch_sql",
    run_type="chain",
    tags=["retrieval", "sql", "branch"],
)
@node_span("sql")
async def run_sql_retrieval_async(
    query: str,
    config: RunnableConfig,
    sql_question: str | None = None,
) -> dict:
    """
    Async SQL retrieval with timeout.

    This function is the semantic SQL boundary: it is the last place that
    knows whether SQL retrieval actually produced usable rows. It keeps
    returning an error payload rather than raising, so a SQL failure still
    leaves vector and market retrieval to complete — which means the
    surrounding `node_span("sql")` correctly reports `ok` even when SQL did
    not succeed. The `[SQL] retrieval` lines below carry that distinction,
    since a span status alone cannot.
    """
    started = time.perf_counter()

    def elapsed_ms() -> float:
        return (time.perf_counter() - started) * 1000

    logger.info("[SQL] retrieval -> start")

    try:
        # run_sql_retrieval is a coroutine — awaiting it directly keeps
        # the LangSmith run context (a contextvar) attached. Handing it
        # to run_in_executor would return the un-awaited coroutine and
        # detach the trace.
        result = await asyncio.wait_for(
            run_sql_retrieval(
                query,
                config,
                sql_question=sql_question,
            ),
            timeout=SQL_TIMEOUT
        )

    except asyncio.TimeoutError:
        # Not an error for the pipeline — retrieval degrades and continues —
        # so this is a warning, and there is no traceback worth printing for
        # a timeout.
        logger.warning(
            "[SQL] retrieval <- timeout %.0fms timeout_ms=%d",
            elapsed_ms(),
            SQL_TIMEOUT * 1000,
        )
        return {
            "source": "sql",
            "answer": "",
            "confidence": 0.0,
            "error": "timeout"
        }

    except Exception as e:
        # The only place this exception is seen, so it keeps its traceback.
        logger.error(
            "[SQL] retrieval <- failed %.0fms error=%s",
            elapsed_ms(),
            type(e).__name__,
            exc_info=True,
        )
        return {
            "source": "sql",
            "answer": "",
            "confidence": 0.0,
            "error": str(e)
        }

    # A failure inside run_sql_retrieval was already converted into an error
    # payload there, so it arrives as a normal return. Without this check the
    # boundary would report `ok` for a run that retrieved nothing.
    if result.get("error"):
        # Already logged with its message one level down; a concise status is
        # enough here, and the class name avoids putting a driver's error
        # text — which can include connection details — on this line.
        logger.warning(
            "[SQL] retrieval <- failed %.0fms error=%s",
            elapsed_ms(),
            result.get("error_type") or "SQLRetrievalError",
        )
        return result

    logger.info(
        "[SQL] retrieval <- ok %.0fms rows=%d",
        elapsed_ms(),
        len(extract_sql_rows(result.get("db_result"))),
    )
    return result
    

